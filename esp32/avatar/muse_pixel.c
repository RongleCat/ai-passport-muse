/* Iris pixels in sprite space. A blink covers these and leaves the hair alone. */
static const uint8_t IRIS_L[IRIS_L_N * 2] = { 19,22, 20,21, 21,21, 22,21, 22,22, 22,23, 22,24, 22,25, 23,21, 23,22, 23,23, 23,24, 23,25, 24,21, 24,22, 24,23, 24,24, 24,25, 25,21, 25,22, 25,23, 25,24, 25,25, 26,22, 26,23, 26,24, 26,25, 27,22, 27,23 };
static const uint8_t IRIS_R[IRIS_R_N * 2] = { 44,26, 44,27, 44,28, 44,29, 45,26, 45,27, 45,28, 45,29, 46,26, 46,27, 46,28, 46,29, 46,30, 47,26, 47,27, 47,28, 47,29, 47,30, 48,26, 48,27, 48,28, 48,29 };

static rgb_t s_scheme[5];
static bool s_scheme_init;
static uint16_t s_pal[C_COUNT];
static uint16_t s_pal_dim[C_COUNT];
static uint8_t s_fb[W * H];

static const uint8_t BAYER4[4][4] = {
    { 0, 8, 2, 10 },
    { 12, 4, 14, 6 },
    { 3, 11, 1, 9 },
    { 15, 7, 13, 5 },
};

static inline int iround(float v) { return (int)floorf(v + 0.5f); }
static inline float clampf(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
static inline float fracf(float v) { return v - floorf(v); }
static inline float bayer(int x, int y) { return (BAYER4[y & 3][x & 3] + 0.5f) / 16.0f; }

static inline rgb_t hex_rgb(uint32_t c)
{
    return (rgb_t){ (float)((c >> 16) & 0xff), (float)((c >> 8) & 0xff), (float)(c & 0xff) };
}

static inline rgb_t mix(rgb_t a, rgb_t b, float t)
{
    return (rgb_t){ a.r + (b.r - a.r) * t, a.g + (b.g - a.g) * t, a.b + (b.b - a.b) * t };
}

static inline rgb_t scale_rgb(rgb_t a, float k)
{
    return (rgb_t){ a.r * k, a.g * k, a.b * k };
}

static inline uint16_t to565(rgb_t c)
{
    int r = (int)(c.r + 0.5f), g = (int)(c.g + 0.5f), b = (int)(c.b + 0.5f);
    r = r < 0 ? 0 : (r > 255 ? 255 : r);
    g = g < 0 ? 0 : (g > 255 ? 255 : g);
    b = b < 0 ? 0 : (b > 255 ? 255 : b);
    return (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
}

uint32_t muse_pixel_accent(muse_mode_t mode)
{
    return SCHEMES[mode < MUSE_MODE_COUNT ? mode : MUSE_MODE_IDLE].acc;
}

static void update_palette(const scheme_t *target, float dt)
{
    rgb_t tgt[5];
    for (int i = 0; i < 4; i++) {
        tgt[i] = hex_rgb(target->f[i]);
    }
    tgt[4] = hex_rgb(target->acc);
    float k = s_scheme_init ? 1.0f - expf(-dt * 7.0f) : 1.0f;
    for (int i = 0; i < 5; i++) {
        s_scheme[i] = mix(s_scheme[i], tgt[i], k);
    }
    s_scheme_init = true;

    rgb_t pal[C_COUNT];
    for (int i = 0; i < C_COUNT; i++) {
        pal[i] = hex_rgb(FIXED[i]);
    }
    rgb_t acc = s_scheme[4];
    pal[C_G0] = s_scheme[0];
    pal[C_G1] = s_scheme[1];
    pal[C_G2] = s_scheme[2];
    pal[C_G3] = s_scheme[3];
    pal[C_ACC] = acc;
    pal[C_AURA1] = scale_rgb(acc, 0.16f);
    pal[C_AURA2] = scale_rgb(acc, 0.34f);
    pal[C_SPK] = mix(acc, hex_rgb(0xffffff), 0.45f);
    for (int i = 0; i < C_COUNT; i++) {
        s_pal[i] = to565(pal[i]);
        s_pal_dim[i] = to565(scale_rgb(pal[i], 0.72f));
    }
}

static inline void px(int x, int y, uint8_t c)
{
    if ((unsigned)x < W && (unsigned)y < H) {
        s_fb[y * W + x] = c;
    }
}

static inline uint8_t get_px(int x, int y)
{
    if ((unsigned)x < W && (unsigned)y < H) {
        return s_fb[y * W + x];
    }
    return C_BG;
}

static uint32_t s_rng = 0x9e3779b9u;
static float frand(void)
{
    s_rng ^= s_rng << 13;
    s_rng ^= s_rng >> 17;
    s_rng ^= s_rng << 5;
    return (float)(s_rng & 0xffffff) / (float)0x1000000;
}

typedef struct {
    float next_blink;
    float blink_start;
    float last_t;
} eyes_t;

static eyes_t s_eyes = { .next_blink = 1.5f, .blink_start = -10 };

static float eyes_update(const muse_pose_t *p, float dt)
{
    (void)dt;
    eyes_t *e = &s_eyes;
    if (p->t >= e->next_blink) {
        e->blink_start = p->t;
        e->next_blink = p->t + (frand() < 0.2f ? 0.28f : 2.2f + frand() * 3.0f);
    }
    float bt = (p->t - e->blink_start) / 0.16f;
    if (bt < 0 || bt > 1) {
        return 0;
    }
    return 1.0f - fabsf(bt * 2 - 1);
}

static void blit(int ox, int oy)
{
    for (int y = 0; y < H; y++) {
        int dy = y + oy;
        if ((unsigned)dy >= H) {
            continue;
        }
        for (int x = 0; x < W; x++) {
            uint8_t c = SPRITE[y * W + x];
            int dx = x + ox;
            if (c && (unsigned)dx < W) {
                s_fb[dy * W + dx] = c;
            }
        }
    }
}

static void blink_pts(const uint8_t *xy, int n, int ox, int oy, float amount)
{
    if (n <= 0 || amount <= 0) {
        return;
    }
    int y0 = xy[1], y1 = xy[1];
    for (int i = 1; i < n; i++) {
        int y = xy[i * 2 + 1];
        if (y < y0) {
            y0 = y;
        }
        if (y > y1) {
            y1 = y;
        }
    }
    int limit = y0 + (int)(amount * (y1 - y0 + 1) + 0.5f);
    for (int i = 0; i < n; i++) {
        if (xy[i * 2 + 1] < limit) {
            px(xy[i * 2] + ox, xy[i * 2 + 1] + oy, SKIN_IX);
        }
    }
}

static void draw_aura(int cx, int cy, int radius)
{
    int r2 = radius * radius;
    for (int y = cy - radius; y <= cy + radius; y++) {
        for (int x = cx - radius; x <= cx + radius; x++) {
            int dx = x - cx, dy = y - cy;
            int d2 = dx * dx + dy * dy;
            if (d2 >= r2 || get_px(x, y) != C_BG) {
                continue;
            }
            float e = (float)d2 / (float)r2;
            if (bayer(x, y) > e) {
                px(x, y, e < 0.55f ? C_AURA2 : C_AURA1);
            }
        }
    }
}

static void draw_rings(float cx, float cy, float t, float level, float speed)
{
    for (int k = 0; k < 2; k++) {
        float ph = fracf(t * speed + k * 0.5f);
        float r = 22 + ph * 8;
        float fade = (1 - ph) * (0.35f + level);
        int n = (int)(r * 1.6f);
        for (int i = 0; i < n; i++) {
            float a = i * TAU / n;
            int x = iround(cx + cosf(a) * r);
            int y = iround(cy + sinf(a) * r * 0.72f);
            if (get_px(x, y) == C_BG && bayer(x, y) < fade) {
                px(x, y, k ? C_G1 : C_ACC);
            }
        }
    }
}

static void draw_sparkles(float t, float cx, float cy, float speed, int count)
{
    for (int i = 0; i < count; i++) {
        float a = t * speed + i * TAU / (count > 0 ? count : 1);
        float rr = 26.0f;
        int x = iround(cx + cosf(a) * rr);
        int y = iround(cy + sinf(a) * rr * 0.45f);
        if (get_px(x, y) == C_BG) {
            px(x, y, C_SPK);
        }
    }
}

static void draw_thought(float x, float y, float t)
{
    int active = (int)(fracf(t * 1.6f) * 3.0f);
    for (int i = 0; i < 3; i++) {
        int bx = iround(x + i * 4);
        int by = iround(y - i * 3);
        uint8_t c = i == active ? C_G0 : C_ACC;
        px(bx, by, c);
        px(bx + 1, by, c);
        px(bx, by + 1, c);
        px(bx + 1, by + 1, c);
    }
}

static void draw_hearts(float cx, float top, float t, float amount)
{
    static const char *const HEART[] = { ".#.#.", "#o###", "#####", ".###.", "..#.." };
    for (int i = 0; i < 2; i++) {
        float ph = fracf(t * 0.9f + i * 0.5f);
        if (ph > amount) {
            continue;
        }
        int hx = iround(cx + (i ? 16 : -20));
        int hy = iround(top - ph * 8);
        for (int r = 0; r < 5; r++) {
            for (int c = 0; HEART[r][c]; c++) {
                if (HEART[r][c] == '#') {
                    px(hx + c, hy + r, C_HEART);
                } else if (HEART[r][c] == 'o') {
                    px(hx + c, hy + r, C_G0);
                }
            }
        }
    }
}

static void draw_alert(int x, int y)
{
    static const char *const BANG[] = { ".##.", ".##.", ".##.", ".##.", "....", ".##." };
    for (int r = 0; r < 6; r++) {
        for (int c = 0; BANG[r][c]; c++) {
            if (BANG[r][c] == '#') {
                px(x + c, y + r, C_ACC);
            }
        }
    }
}

#define MAP_MAX 512
static uint8_t s_map[MAP_MAX];
static int s_size;

void muse_pixel_set_size(int px_n)
{
    s_size = px_n < MAP_MAX ? px_n : MAP_MAX;
    bool grid = s_size >= 3 * W;
    for (int i = 0; i < s_size; i++) {
        int cell = i * W / s_size;
        bool edge = grid && (i + 1) * W / s_size != cell;
        s_map[i] = (uint8_t)(cell | (edge ? 0x80 : 0));
    }
}

void muse_pixel_scale(uint16_t *dst, int stride_px, int x0, int x1, int y0, int y1)
{
    int n = x1 - x0 + 1;
    const uint8_t *xmap = &s_map[x0];
    const uint16_t *prev = NULL;
    uint8_t prev_m = 0;
    for (int y = y0; y <= y1; y++, dst += stride_px) {
        uint8_t m = s_map[y];
        if (prev && m == prev_m) {
            memcpy(dst, prev, n * sizeof(uint16_t));
            continue;
        }
        const uint8_t *row = &s_fb[(m & 0x7f) * W];
        if (m & 0x80) {
            for (int i = 0; i < n; i++) {
                dst[i] = s_pal_dim[row[xmap[i] & 0x7f]];
            }
        } else {
            for (int i = 0; i < n; i++) {
                uint8_t xm = xmap[i];
                uint8_t c = row[xm & 0x7f];
                dst[i] = xm & 0x80 ? s_pal_dim[c] : s_pal[c];
            }
        }
        prev = dst;
        prev_m = m;
    }
}

void muse_pixel_render(const muse_pose_t *p)
{
    float dt = s_eyes.last_t > 0 ? clampf(p->t - s_eyes.last_t, 0, 0.2f) : 0.04f;
    s_eyes.last_t = p->t;
    muse_mode_t mode = p->mode;
    update_palette(&SCHEMES[mode], dt);
    float blink = eyes_update(p, dt);
    memset(s_fb, C_BG, sizeof(s_fb));

    float t = p->t;
    float level = p->level;
    float happy = p->happy;
    float bob = sinf(t * 1.8f);
    float lean = 0;
    if (mode == MUSE_MODE_LISTENING) {
        bob = sinf(t * 3.0f) * 0.6f;
    } else if (mode == MUSE_MODE_THINKING) {
        bob = sinf(t * 2.4f) * 0.8f;
        lean = sinf(t * 1.3f) * 1.2f;
    } else if (mode == MUSE_MODE_SPEAKING) {
        bob = sinf(t * 5.0f) * 0.6f;
    } else if (mode == MUSE_MODE_ERROR) {
        lean = sinf(t * 18.0f) * (p->mode_t < 0.6f ? 1.0f : 0.0f);
        bob = 0;
    }
    float hop = happy > 0 ? fabsf(sinf(t * 9.0f)) * 2.0f * happy : 0;
    int ox = iround(lean);
    int oy = iround(bob * 0.5f - hop);
    if (mode == MUSE_MODE_BOOT) {
        float pop = clampf(p->mode_t / 0.6f, 0, 1);
        oy += (int)((1.0f - pop) * 10);
    }

    draw_aura(32, 34, 30);
    if (mode == MUSE_MODE_LISTENING) {
        draw_rings(32, 30, t, level, 0.9f);
    } else if (mode == MUSE_MODE_SPEAKING) {
        draw_rings(32, 30, t, level, 0.6f);
    }
    blit(ox, oy);

    float open = 1.0f - blink;
    if (mode == MUSE_MODE_BOOT && p->mode_t < 0.9f) {
        open = 0;
    } else if (mode == MUSE_MODE_OFF) {
        open = clampf((1.0f - p->mode_t / 1.0f) * 1.5f, 0, 1);
    } else if (mode == MUSE_MODE_ERROR) {
        open = 0;
    }
    if (open < 0.85f && mode != MUSE_MODE_ERROR) {
        blink_pts(IRIS_L, IRIS_L_N, ox, oy, 1.0f - open);
        blink_pts(IRIS_R, IRIS_R_N, ox, oy, 1.0f - open);
    }
    if (mode == MUSE_MODE_ERROR) {
        /* Flat lids. The portrait underneath stays the reference. */
        blink_pts(IRIS_L, IRIS_L_N, ox, oy, 0.55f);
        blink_pts(IRIS_R, IRIS_R_N, ox, oy, 0.55f);
        draw_alert(50, 6);
    }

    if (mode == MUSE_MODE_OFF) {
        float fade = clampf(p->mode_t / 1.3f, 0, 1);
        for (int y = 0; y < H; y++) {
            for (int x = 0; x < W; x++) {
                if (s_fb[y * W + x] && bayer(x, y) < fade) {
                    s_fb[y * W + x] = C_BG;
                }
            }
        }
    }

    int sparks = mode == MUSE_MODE_BOOT ? (int)(clampf(p->mode_t / 1.4f, 0, 1) * 5) : 5;
    if (mode == MUSE_MODE_OFF) {
        sparks = (int)((1.0f - clampf(p->mode_t / 1.3f, 0, 1)) * 5);
    }
    draw_sparkles(t, 32, 32, mode == MUSE_MODE_THINKING ? 2.4f : 0.7f, sparks);
    if (mode == MUSE_MODE_THINKING) {
        draw_thought(46, 14, t);
    }
    if (happy > 0 && mode != MUSE_MODE_ERROR) {
        draw_hearts(32, 8, t, happy);
    }
}
